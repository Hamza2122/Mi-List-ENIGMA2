#!/bin/sh

# ==========================================
# إعدادات المستودع (قم بتعديلها بما يناسبك)
# ==========================================
URL="https://github.com/Hamza2122/Mi-List-ENIGMA2/raw/refs/heads/main/MIList.tar.gz"
TMP_FILE="/tmp/MIList.tar.gz"

echo "=========================================="
echo "   جاري تحديث ملف القنوات من GitHub...    "
echo "=========================================="

# 1. تحميل ملف القنوات المضغوط
echo "-> 1. جاري تحميل الملف..."
wget --no-check-certificate -q -O "$TMP_FILE" "$URL"

# التحقق من نجاح التحميل وأن الملف غير فارغ
if [ ! -s "$TMP_FILE" ]; then
    echo "خطأ: فشل تحميل الملف! تأكد من الرابط أو الاتصال بالإنترنت."
    rm -f "$TMP_FILE"
    exit 1
fi

# 2. حذف القنوات والباقات القديمة لتجنب التكرار
echo "-> 2. جاري تنظيف القنوات القديمة..."
rm -rf /etc/enigma2/lamedb*
rm -rf /etc/enigma2/*.tv
rm -rf /etc/enigma2/*.radio
rm -rf /etc/enigma2/blacklist
rm -rf /etc/enigma2/whitelist

# 3. فك الضغط في المسار الجذري
echo "-> 3. جاري تثبيت القنوات الجديدة..."
tar -xzf "$TMP_FILE" -C /

# 4. حذف الملف المؤقت
rm -f "$TMP_FILE"

# 5. تحديث قائمة القنوات على الشاشة فوراً
echo "-> 4. جاري تحديث الواجهة..."
wget -qO - http://127.0.0 > /dev/null 2>&1

echo "=========================================="
echo "     تم تحديث ملف القنوات بنجاح!         "
echo "=========================================="
exit 0
